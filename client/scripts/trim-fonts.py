#!/usr/bin/env python3
"""Trim the self-hosted variable fonts to the weights the site uses.

The fontsource packages ship each face's full weight axis (Newsreader
200-800, Schibsted Grotesk 400-900). The site only uses part of it, and the
axis range is most of each file's size, so this narrows the weight axis with
fontTools' instancer and keeps everything else: the optical-size axis
(font-optical-sizing: auto on the display face), every glyph, and the same
latin / latin-ext / vietnamese unicode-range split.

Run after changing a weight in use or upgrading a font package:
    pip install fonttools brotli
    cd client && python3 scripts/trim-fonts.py
It rewrites src/assets/fonts/*.woff2 and src/fonts.css (both committed, so
the normal build needs no Python).
"""
import pathlib
import re

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODULES = ROOT / 'node_modules' / '@fontsource-variable'
OUT_DIR = ROOT / 'src' / 'assets' / 'fonts'
CSS_OUT = ROOT / 'src' / 'fonts.css'

# (package, fontsource stylesheet, weight range kept). Keep these in step
# with the weights used: Newsreader 400-720 (720 is the hero's proximity peak,
# hooks/useProximityWeight.js; the cover canvas draws at 500 and 600); its
# italic only sets captions and notes (400-600); Schibsted 400-800 (800 is
# the rubber stamp's extrabold).
#
# The Hebrew edition's faces keep only their Hebrew subset: Latin text on a
# Hebrew page still sets in Newsreader / Schibsted (earlier in the stack),
# and an English reader never downloads either, since the browser fetches a
# face only when the page holds a character in its unicode-range.
FACES = [
    ('newsreader', 'opsz.css', (400, 720), None),
    ('newsreader', 'opsz-italic.css', (400, 600), None),
    ('schibsted-grotesk', 'wght.css', (400, 800), None),
    ('frank-ruhl-libre', 'wght.css', (400, 720), 'hebrew'),
    ('heebo', 'wght.css', (400, 800), 'hebrew'),
]


def trim(src: pathlib.Path, dest: pathlib.Path, low: int, high: int) -> None:
    font = TTFont(src)
    instantiateVariableFont(font, {'wght': (low, high)}, inplace=True)
    font.flavor = 'woff2'
    font.save(dest)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    css = ['/* Generated by scripts/trim-fonts.py from the fontsource stylesheets. Do not edit. */\n']
    before = after = 0
    for package, sheet, (low, high), subset in FACES:
        text = (MODULES / package / sheet).read_text()
        if subset:
            blocks = re.findall(r'/\* [\w-]+ \*/\s*@font-face \{[^}]*\}', text)
            text = '\n\n'.join(b for b in blocks if f'-{subset}-' in b.split('*/')[0]) + '\n'
        for name in re.findall(r'url\(\./files/([\w.-]+\.woff2)\)', text):
            src = MODULES / package / 'files' / name
            dest = OUT_DIR / name
            trim(src, dest, low, high)
            before += src.stat().st_size
            after += dest.stat().st_size
            print(f'{name}: {src.stat().st_size} -> {dest.stat().st_size}')
        text = text.replace('url(./files/', 'url(./assets/fonts/')
        text = re.sub(r'font-weight: \d+ \d+;', f'font-weight: {low} {high};', text)
        css.append(text)
    CSS_OUT.write_text('\n'.join(css))
    print(f'total {before} -> {after} bytes')


if __name__ == '__main__':
    main()
